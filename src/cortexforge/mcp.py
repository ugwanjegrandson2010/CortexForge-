"""MCP integration — pre-configured servers, OAuth-only for the user.

The requirement: CortexForge ships with its MCP servers already declared, so
the learner's only remaining action is to authorise (OAuth). This module
holds the catalogue, the config generator, and the OAuth discovery client.

Design rules:
  * A server entry declares its transport and auth. `auth: "oauth"` entries
    are the ones the user must authorise; everything else is pre-wired.
  * Secrets never live in the generated config. OAuth tokens are written to
    the OS keyring or a 0600 file outside the repo, and the config holds only
    the server URL and the token *reference*.
  * Outbound URLs pass through security.validate_outbound_url before any
    request, and again after every redirect (SSRF control).
  * Discovery follows RFC 9470 (protected resource metadata) then RFC 8414
    (authorization server metadata), which is what Notion and the other
    hosted MCP servers implement.
"""

