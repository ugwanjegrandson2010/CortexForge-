CATALOGUE_BY_KEY = {s.key: s for s in CATALOGUE}

# The set CortexForge enables by default. Chosen so that a learner can go
# from "I have notes and a textbook" to a working system with the fewest
# possible authorisations.
CORE_KEYS = [
    "notion", "obsidian", "anki", "arxiv", "github",
    "memory", "fetch", "context7", "youtube", "zotero",
    "google_drive", "playwright",
]


def core_servers() -> list[MCPServer]:
    return [CATALOGUE_BY_KEY[k] for k in CORE_KEYS if k in CATALOGUE_BY_KEY]


def oauth_servers() -> list[MCPServer]:
    """Servers the learner must authorise — the only manual step."""
    return [s for s in CATALOGUE if s.auth == AUTH_OAUTH]


def servers_needing_secrets() -> list[MCPServer]:
    return [s for s in CATALOGUE if s.auth == AUTH_API_KEY]


# ---------------------------------------------------------------------------
# Config generation
# ---------------------------------------------------------------------------

def build_mcp_config(keys: list[str] | None = None,
                     token_dir: str | Path | None = None) -> dict:
    """Generate an mcpServers config block for the requested servers.

    Secrets are never inlined. API-key servers reference an environment
    variable; OAuth servers carry only their URL, because the token is
    obtained at runtime and stored separately.
    """
    keys = keys or CORE_KEYS
    token_dir = Path(token_dir) if token_dir else Path.home() / ".cortexforge" / "tokens"
    servers: dict[str, Any] = {}
    for key in keys:
        spec = CATALOGUE_BY_KEY.get(key)
        if spec is None:
            continue
        entry: dict[str, Any] = {}
        if spec.transport == "stdio":
            entry["command"] = spec.target
            entry["args"] = list(spec.args)
            if spec.env_keys:
                entry["env"] = {k: f"${{{k}}}" for k in spec.env_keys}
        else:
            entry["type"] = spec.transport
            entry["url"] = spec.target
            if spec.auth == AUTH_OAUTH:
                entry["auth"] = "oauth"
                entry["token_cache"] = str(
                    safe_join(token_dir, f"{spec.key}.json"))
        entry["_cortexforge"] = {
            "name": spec.name,
            "category": spec.category,
            "learning_role": spec.learning_role,
            "auth": spec.auth,
        }
        servers[spec.key] = entry
    return {"mcpServers": servers}


def write_mcp_config(path: str | Path, keys: list[str] | None = None) -> Path:
    """Write the config with 0600 permissions (it names token cache paths)."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    cfg = build_mcp_config(keys)
    p.write_text(json.dumps(cfg, indent=2), encoding="utf-8")
    try:
        os.chmod(p, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        pass
    return p


