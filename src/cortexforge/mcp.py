# ---------------------------------------------------------------------------
# OAuth discovery (RFC 9470 + RFC 8414)
# ---------------------------------------------------------------------------

def discover_oauth(url: str, timeout: float = 10.0) -> dict:
    """Discover the authorization server for a protected MCP resource.

    Step 1: fetch <resource>/.well-known/oauth-protected-resource (RFC 9470)
    Step 2: fetch <auth_server>/.well-known/oauth-authorization-server (RFC 8414)

    Every URL is validated before the request. Returns a dict describing the
    endpoints, or raises SecurityError.
    """
    import urllib.error
    import urllib.request

    resource = validate_outbound_url(url)
    meta_url = resource.rstrip("/") + "/.well-known/oauth-protected-resource"
    meta = _fetch_json(meta_url, timeout)
    auth_servers = meta.get("authorization_servers") or []
    if not auth_servers:
        raise SecurityError("no authorization_servers in resource metadata")
    as_url = validate_outbound_url(auth_servers[0])
    as_meta_url = as_url.rstrip("/") + "/.well-known/oauth-authorization-server"
    as_meta = _fetch_json(as_meta_url, timeout)
    required = ("authorization_endpoint", "token_endpoint")
    missing = [k for k in required if k not in as_meta]
    if missing:
        raise SecurityError(f"authorization metadata missing: {missing}")
    return {
        "resource": resource,
        "authorization_server": as_url,
        "authorization_endpoint": validate_outbound_url(as_meta["authorization_endpoint"]),
        "token_endpoint": validate_outbound_url(as_meta["token_endpoint"]),
        "registration_endpoint": (
            validate_outbound_url(as_meta["registration_endpoint"])
            if as_meta.get("registration_endpoint") else None),
        "scopes_supported": as_meta.get("scopes_supported", []),
        "pkce_required": "S256" in (as_meta.get("code_challenge_methods_supported") or []),
    }


def _fetch_json(url: str, timeout: float) -> dict:
    """Fetch and parse JSON with size, redirect, and content-type guards."""
    import urllib.error
    import urllib.request

    class _NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, req, fp, code, msg, headers, newurl):
            # Re-validate the redirect target; never follow blindly (SSRF).
            validate_outbound_url(newurl)
            return super().redirect_request(req, fp, code, msg, headers, newurl)

    opener = urllib.request.build_opener(_NoRedirect())
    req = urllib.request.Request(url, headers={
        "Accept": "application/json",
        "User-Agent": "CortexForge/1.0 (+local)",
    })
    try:
        with opener.open(req, timeout=timeout) as resp:
            ctype = resp.headers.get("Content-Type", "")
            if "json" not in ctype.lower():
                raise SecurityError(f"unexpected content-type: {ctype!r}")
            raw = resp.read(1_000_000)  # 1 MiB cap
    except urllib.error.URLError as exc:
        raise SecurityError(f"discovery request failed: {exc}") from None
    return load_json_only(raw.decode("utf-8", "replace"))


