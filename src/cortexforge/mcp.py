def store_token(token_dir: str | Path, server_key: str, token: dict) -> Path:
    """Persist an OAuth token with 0600 permissions, outside the repo."""
    d = Path(token_dir)
    d.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(d, stat.S_IRWXU)
    except OSError:
        pass
    path = safe_join(d, f"{server_key}.json")
    payload = dict(token)
    payload["_stored_at"] = time.time()
    path.write_text(json.dumps(payload), encoding="utf-8")
    try:
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        pass
    return path


def load_token(token_dir: str | Path, server_key: str) -> dict | None:
    path = safe_join(Path(token_dir), f"{server_key}.json")
    if not path.is_file():
        return None
    return load_json_only(path.read_text(encoding="utf-8"))


def token_status(token_dir: str | Path, server_key: str) -> dict:
    tok = load_token(token_dir, server_key)
    if not tok:
        return {"server": server_key, "authorised": False}
    expires = tok.get("expires_at")
    expired = bool(expires and time.time() > float(expires))
    return {
        "server": server_key,
        "authorised": True,
        "expired": expired,
        "has_refresh": bool(tok.get("refresh_token")),
        "access_token": redact(str(tok.get("access_token", ""))),
    }
